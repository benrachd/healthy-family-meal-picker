function tags(r: Pick<Recipe, 'proteinFriendly' | 'kidFriendly' | 'budgetFriendly' | 'makeAhead'>): string[] {
  const t: string[] = []
  if (r.proteinFriendly) t.push('High Protein')
  if (r.kidFriendly) t.push('Kid Friendly')
  if (r.budgetFriendly) t.push('Budget Friendly')
  if (r.makeAhead) t.push('Make Ahead')
  return t
}

function recipe(
  partial: Omit<Recipe, 'tags'> & { makeAhead?: boolean }
): Recipe {
  return { ...partial, tags: tags(partial) }
}

